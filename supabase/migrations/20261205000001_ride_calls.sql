-- In-app voice calls between a passenger and the driver assigned to the same ride.
-- Only signalling and history live here: the audio itself goes through the calling provider
-- (LiveKit or Agora) and is never recorded or stored.
create table if not exists app.ride_calls (
  id bigint generated by default as identity primary key,
  ride_request_id bigint not null references app.ride_requests(id) on delete cascade,
  driver_id bigint not null references app.users(id),
  rider_id bigint not null references app.users(id),
  caller_id bigint not null references app.users(id),
  callee_id bigint not null references app.users(id),
  provider text not null check (provider in ('livekit', 'agora')),
  room text not null,
  status text not null default 'ringing'
    check (status in ('ringing', 'active', 'ended', 'declined', 'missed', 'cancelled', 'failed')),
  end_reason text,
  created_at timestamptz not null default now(),
  answered_at timestamptz,
  ended_at timestamptz,
  duration_seconds integer,
  check (caller_id <> callee_id)
);

-- One live call per ride, enforced by the database.
create unique index if not exists ride_calls_one_live_per_ride on app.ride_calls (ride_request_id) where status in ('ringing', 'active');
create index if not exists ride_calls_ride_idx on app.ride_calls (ride_request_id, id desc);
create index if not exists ride_calls_callee_live_idx on app.ride_calls (callee_id) where status = 'ringing';

alter table app.ride_calls enable row level security;
