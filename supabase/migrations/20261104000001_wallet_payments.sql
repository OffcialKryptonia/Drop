-- Wallet and payments foundation. Money is numeric(14,2), never float.
-- Gateway SECRETS are never stored here (they live in Worker secrets).

create table app.wallets (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null unique references app.users (id) on delete cascade,
  currency    char(3) not null default 'NGN',
  balance     numeric(14,2) not null default 0 check (balance >= 0),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create trigger wallets_touch before update on app.wallets
  for each row execute function app.touch_updated_at();

-- Append-only ledger. balance_after is the wallet balance right after this row.
create table app.wallet_ledger (
  id               bigint generated by default as identity primary key,
  wallet_id        bigint not null references app.wallets (id) on delete restrict,
  user_id          bigint not null references app.users (id) on delete restrict,
  direction        text not null check (direction in ('credit', 'debit')),
  amount           numeric(14,2) not null check (amount > 0),
  balance_after    numeric(14,2) not null check (balance_after >= 0),
  kind             text not null check (kind in ('topup', 'ride_payment', 'ride_earning', 'commission',
                                                  'withdrawal', 'refund', 'adjustment', 'legacy_import')),
  ride_request_id  bigint,
  description      text,
  idempotency_key  text not null unique,           -- a replayed event can never post twice
  meta             jsonb not null default '{}'::jsonb,
  created_at       timestamptz not null default now()
);
create index wallet_ledger_user_idx on app.wallet_ledger (user_id, created_at desc);

-- Which gateways the apps may show. No keys here.
create table app.payment_gateways (
  id          bigint generated by default as identity primary key,
  type        text not null unique check (type in ('wallet', 'cash', 'pocketfi', 'korapay', 'paystack', 'flutterwave')),
  title       text not null,
  status      boolean not null default true,
  is_test     boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create trigger payment_gateways_touch before update on app.payment_gateways
  for each row execute function app.touch_updated_at();

-- A user's dedicated bank account at a provider (bank-transfer top-up).
create table app.virtual_accounts (
  id                 bigint generated by default as identity primary key,
  user_id            bigint not null references app.users (id) on delete cascade,
  provider           text not null check (provider in ('pocketfi', 'korapay', 'paystack')),
  provider_customer  text,                          -- provider's customer id (webhook key)
  bank_name          text not null,
  account_number     text not null,
  account_name       text,
  status             text not null default 'active' check (status in ('active', 'suspended')),
  created_at         timestamptz not null default now(),
  unique (provider, account_number),
  unique (user_id, provider, bank_name)
);
create index virtual_accounts_customer_idx on app.virtual_accounts (provider, provider_customer);

-- Every inbound provider event, stored once. unique(provider, provider_reference) makes replays harmless.
create table app.payment_events (
  id                  bigint generated by default as identity primary key,
  provider            text not null,
  provider_reference  text not null,
  user_id             bigint references app.users (id) on delete set null,
  amount              numeric(14,2),
  fee                 numeric(14,2),
  status              text not null default 'received'
                        check (status in ('received', 'credited', 'ignored', 'flagged')),
  note                text,
  payload             jsonb not null,                -- masked by the provider; contains no secrets
  created_at          timestamptz not null default now(),
  unique (provider, provider_reference)
);

alter table app.wallets          enable row level security;
alter table app.wallet_ledger    enable row level security;
alter table app.payment_gateways enable row level security;
alter table app.virtual_accounts enable row level security;
alter table app.payment_events   enable row level security;

