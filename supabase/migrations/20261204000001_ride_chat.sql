-- Ride chat: text and voice messages between a passenger and the driver assigned to that ride.
-- Audio files live in the private R2 bucket; only the key and metadata are stored here.
create table app.ride_messages (
  id              bigint generated by default as identity primary key,
  ride_request_id bigint      not null references app.ride_requests (id) on delete cascade,
  driver_id       bigint      not null references app.users (id),
  rider_id        bigint      not null references app.users (id),
  sender_id       bigint      not null references app.users (id),
  kind            text        not null check (kind in ('text', 'voice')),
  body            text        check (body is null or length(body) <= 1000),
  audio_key       text,
  audio_seconds   integer     check (audio_seconds is null or audio_seconds between 1 and 600),
  audio_bytes     integer,
  waveform        smallint[],
  client_id       text        not null check (length(client_id) between 8 and 64),
  delivered_at    timestamptz,
  read_at         timestamptz,
  created_at      timestamptz not null default now(),
  unique (ride_request_id, sender_id, client_id),
  check ((kind = 'text' and body is not null and length(btrim(body)) > 0) or (kind = 'voice' and audio_key is not null))
);
create index ride_messages_ride_idx on app.ride_messages (ride_request_id, id);
create index ride_messages_created_idx on app.ride_messages (created_at);
alter table app.ride_messages enable row level security;

-- Who has the chat open right now (so a push is skipped when the other person is already looking).
create table app.ride_chat_presence (
  ride_request_id bigint      not null references app.ride_requests (id) on delete cascade,
  user_id         bigint      not null references app.users (id),
  seen_at         timestamptz not null default now(),
  primary key (ride_request_id, user_id)
);
alter table app.ride_chat_presence enable row level security;
