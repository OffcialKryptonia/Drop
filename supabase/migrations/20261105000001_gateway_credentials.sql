-- Gateway credentials entered by an admin in the dashboard. Values are AES-GCM encrypted by the
-- Worker (key = Worker secret SETTINGS_ENCRYPTION_KEY); the database never sees plaintext.
create table app.gateway_credentials (
  gateway_type text   not null references app.payment_gateways (type) on delete cascade,
  mode         text   not null check (mode in ('test', 'live')),
  field        text   not null,
  value_enc    text   not null,                 -- base64(iv) ":" base64(ciphertext)
  is_secret    boolean not null,
  last4        text,                            -- shown in the UI for secrets
  updated_by   bigint references app.users (id) on delete set null,
  updated_at   timestamptz not null default now(),
  primary key (gateway_type, mode, field)
);

create table app.admin_audit (
  id         bigint generated by default as identity primary key,
  admin_id   bigint references app.users (id) on delete set null,
  action     text not null,
  target     text,
  detail     jsonb not null default '{}'::jsonb,   -- never contains secret values
  created_at timestamptz not null default now()
);

alter table app.gateway_credentials enable row level security;
alter table app.admin_audit         enable row level security;

