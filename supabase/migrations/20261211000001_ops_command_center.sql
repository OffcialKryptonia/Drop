-- Live Operations Command Center: the history of what dispatchers did to a ride, and operational escalations.
-- Nothing here changes the ride lifecycle, wallets or commission. Assignment, reassignment and cancellation use the
-- existing ride_requests columns and the existing one-open-ride-per-driver and per-rider unique indexes.

-- Every dispatcher action on a ride, with who did it and to whom. Shown on the ride's timeline.
create table app.ride_dispatch_events (
  id               bigint generated by default as identity primary key,
  ride_request_id  bigint not null references app.ride_requests (id) on delete cascade,
  action           text not null check (action in ('assign', 'reassign', 'cancel', 'escalate', 'escalation_resolved', 'contact_view', 'message')),
  admin_id         bigint references app.users (id) on delete set null,
  from_driver_id   bigint references app.users (id) on delete set null,
  to_driver_id     bigint references app.users (id) on delete set null,
  reason           text,
  detail           jsonb not null default '{}'::jsonb,   -- ids and field names only, never phone numbers or message text
  created_at       timestamptz not null default now()
);
create index ride_dispatch_events_ride_idx on app.ride_dispatch_events (ride_request_id, id);
alter table app.ride_dispatch_events enable row level security;

-- An operational problem raised on a ride. One open escalation per ride and category, so a double tap cannot raise it twice.
create table app.ride_escalations (
  id               bigint generated by default as identity primary key,
  ride_request_id  bigint not null references app.ride_requests (id) on delete cascade,
  category         text not null check (category in ('delay', 'driver_unreachable', 'passenger_unreachable', 'payment', 'safety', 'vehicle', 'other')),
  severity         text not null default 'normal' check (severity in ('normal', 'high', 'urgent')),
  reason           text not null check (length(btrim(reason)) between 3 and 500),
  status           text not null default 'open' check (status in ('open', 'resolved')),
  created_by       bigint references app.users (id) on delete set null,
  created_at       timestamptz not null default now(),
  resolved_by      bigint references app.users (id) on delete set null,
  resolved_at      timestamptz,
  resolution_note  text check (resolution_note is null or length(resolution_note) <= 500)
);
create unique index ride_escalations_open_uq on app.ride_escalations (ride_request_id, category) where status = 'open';
create index ride_escalations_status_idx on app.ride_escalations (status, severity, id desc);
alter table app.ride_escalations enable row level security;

-- The dashboard counts rides by day.
create index if not exists ride_requests_created_idx on app.ride_requests (created_at desc);
create index if not exists ride_requests_completed_idx on app.ride_requests (completed_at) where status = 'completed';
create index if not exists ride_requests_cancelled_idx on app.ride_requests (cancelled_at) where status = 'cancelled';
