-- Driver payout requests. The amount leaves the driver's wallet when they ask; admin pays the bank account
-- by hand and marks it paid, or declines it and the money goes back.
create table app.withdraw_requests (
  id             bigint generated by default as identity primary key,
  user_id        bigint        not null references app.users (id) on delete cascade,
  amount         numeric(14,2) not null check (amount > 0),
  currency       char(3)       not null default 'NGN',
  status         text          not null default 'pending' check (status in ('pending', 'paid', 'declined')),
  bank_name      text,
  bank_code      text,
  account_number text,
  account_name   text,
  admin_note     text,
  created_at     timestamptz   not null default now(),
  processed_at   timestamptz,
  processed_by   bigint
);
create index withdraw_requests_user_idx on app.withdraw_requests (user_id, id desc);
create index withdraw_requests_status_idx on app.withdraw_requests (status, id);
alter table app.withdraw_requests enable row level security;
