-- Extra charges a driver adds after a trip (toll, parking, waiting). The passenger approves and pays
-- from their wallet or in cash, or declines. Limits live in app.settings key 'extras' (defaults in code).
create table app.ride_extras (
  id              bigint generated by default as identity primary key,
  ride_request_id bigint      not null references app.ride_requests (id) on delete cascade,
  driver_id       bigint      not null references app.users (id),
  rider_id        bigint      not null references app.users (id),
  kind            text        not null check (kind in ('toll', 'parking', 'waiting', 'other')),
  note            text,
  amount          numeric(14, 2) not null check (amount > 0),
  currency        text        not null default 'NGN',
  status          text        not null default 'pending' check (status in ('pending', 'paid', 'declined', 'expired', 'cancelled')),
  paid_with       text        check (paid_with in ('wallet', 'cash')),
  commission      numeric(14, 2) not null default 0,
  expires_at      timestamptz not null,
  responded_at    timestamptz,
  created_at      timestamptz not null default now()
);
create index ride_extras_ride_idx on app.ride_extras (ride_request_id);
create index ride_extras_rider_pending_idx on app.ride_extras (rider_id) where status = 'pending';
alter table app.ride_extras enable row level security;
