-- Extra charge types are managed by the admin (fuel hike, toll, parking...). Each says whether DROP takes
-- its commission on that charge (using the ride type's own commission rule) and may cap the amount.
create table app.extra_charge_types (
  id              bigint generated by default as identity primary key,
  name            text        not null check (length(trim(name)) between 2 and 40),
  active          boolean     not null default true,
  take_commission boolean     not null default false,
  max_amount      numeric(14, 2) check (max_amount is null or max_amount > 0),
  sort_order      integer     not null default 0,
  created_at      timestamptz not null default now()
);
alter table app.extra_charge_types enable row level security;
insert into app.extra_charge_types (name, sort_order) values
  ('Fuel hike', 1), ('Toll', 2), ('Parking', 3), ('Waiting time', 4), ('Other', 5);

alter table app.ride_extras drop constraint if exists ride_extras_kind_check;
alter table app.ride_extras
  add column type_id bigint references app.extra_charge_types (id) on delete set null,
  add column label text,
  add column commission_applies boolean not null default false;
