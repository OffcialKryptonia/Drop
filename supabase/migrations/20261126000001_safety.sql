-- SOS alerts (rider or driver presses SOS) and complaints with an admin conversation.
create table if not exists app.sos_alerts (
  id            bigint generated by default as identity primary key,
  user_id       bigint        not null references app.users (id) on delete cascade,
  role          text          not null default 'rider' check (role in ('rider', 'driver')),
  ride_request_id bigint      references app.ride_requests (id) on delete set null,
  latitude      numeric(9, 6),
  longitude     numeric(9, 6),
  message       text,
  context       jsonb         not null default '{}'::jsonb,
  status        text          not null default 'open' check (status in ('open', 'acknowledged', 'resolved')),
  admin_note    text,
  handled_by    bigint,
  handled_at    timestamptz,
  created_at    timestamptz   not null default now()
);
create index if not exists sos_alerts_status_idx on app.sos_alerts (status, id desc);
create index if not exists sos_alerts_user_idx on app.sos_alerts (user_id, id desc);
alter table app.sos_alerts enable row level security;

create table if not exists app.complaints (
  id              bigint generated by default as identity primary key,
  user_id         bigint      not null references app.users (id) on delete cascade,
  role            text        not null default 'rider' check (role in ('rider', 'driver')),
  ride_request_id bigint      references app.ride_requests (id) on delete set null,
  subject         text        not null,
  description     text        not null,
  status          text        not null default 'pending' check (status in ('pending', 'investigating', 'resolved')),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists complaints_user_idx on app.complaints (user_id, id desc);
create index if not exists complaints_status_idx on app.complaints (status, id desc);
alter table app.complaints enable row level security;

create table if not exists app.complaint_comments (
  id           bigint generated by default as identity primary key,
  complaint_id bigint      not null references app.complaints (id) on delete cascade,
  user_id      bigint      not null,
  added_by     text        not null check (added_by in ('user', 'admin')),
  comment      text        not null,
  created_at   timestamptz not null default now()
);
create index if not exists complaint_comments_idx on app.complaint_comments (complaint_id, id);
alter table app.complaint_comments enable row level security;
