-- Ride requests: a passenger asks for a ride; the fare is fixed by the server when the request is made.
create table app.ride_requests (
  id               bigint generated by default as identity primary key,
  rider_id         bigint not null references app.users (id),
  driver_id        bigint references app.users (id),
  service_id       bigint not null references app.services (id),
  region_id        bigint references app.regions (id),
  status           text not null default 'searching'
                     check (status in ('searching', 'accepted', 'arrived', 'in_progress', 'completed', 'cancelled', 'expired')),
  pickup_lat       double precision not null check (pickup_lat between -90 and 90),
  pickup_lng       double precision not null check (pickup_lng between -180 and 180),
  pickup_address   text,
  dropoff_lat      double precision not null check (dropoff_lat between -90 and 90),
  dropoff_lng      double precision not null check (dropoff_lng between -180 and 180),
  dropoff_address  text,
  distance         numeric(12, 3) not null,            -- in the region's unit
  distance_unit    text not null check (distance_unit in ('km', 'mile')),
  duration_minutes numeric(10, 2) not null,
  route_source     text not null check (route_source in ('google', 'estimate')),
  fare             numeric(14, 4) not null check (fare >= 0),
  fare_breakdown   jsonb not null,
  options          jsonb not null default '[]'::jsonb,  -- chosen extras with the price at request time
  payment_method   text not null check (payment_method in ('cash', 'wallet', 'card', 'virtual_account')),
  cancelled_by     text check (cancelled_by in ('rider', 'driver', 'system')),
  cancel_reason    text,
  expires_at       timestamptz,                          -- a request nobody accepts by then becomes 'expired'
  accepted_at      timestamptz,
  arrived_at       timestamptz,
  started_at       timestamptz,
  completed_at     timestamptz,
  cancelled_at     timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index ride_requests_rider_idx on app.ride_requests (rider_id, created_at desc);
create index ride_requests_driver_idx on app.ride_requests (driver_id, created_at desc) where driver_id is not null;
create index ride_requests_open_idx on app.ride_requests (status) where status in ('searching', 'accepted', 'arrived', 'in_progress');
-- A passenger can have only one open request at a time.
create unique index ride_requests_one_open_per_rider on app.ride_requests (rider_id)
  where status in ('searching', 'accepted', 'arrived', 'in_progress');
create trigger ride_requests_touch before update on app.ride_requests
  for each row execute function app.touch_updated_at();
alter table app.ride_requests enable row level security;

insert into app.settings (key, value) values ('ride_request_expiry_seconds', '120'::jsonb), ('nearby_driver_radius_m', '5000'::jsonb)
  on conflict (key) do nothing;
