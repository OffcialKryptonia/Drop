-- A passenger can share a live trip link so someone they trust can follow the ride.
create table app.trip_shares (
  id               bigint generated by default as identity primary key,
  token            text        not null unique,
  ride_request_id  bigint      not null references app.ride_requests (id) on delete cascade,
  user_id          bigint      not null references app.users (id) on delete cascade,
  revoked          boolean     not null default false,
  created_at       timestamptz not null default now(),
  expires_at       timestamptz not null default now() + interval '24 hours'
);
create index trip_shares_ride_idx on app.trip_shares (ride_request_id) where not revoked;
alter table app.trip_shares enable row level security;
