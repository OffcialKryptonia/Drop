-- Phase 7: Safety Center, driver analytics instrumentation, audit protection, and the indexes the reports need.
-- Reversible: supabase/rollback/20261212000001_safety_analytics_finance.down.sql (kept outside migrations/ so it is never applied by accident).
-- Nothing here changes wallets, ride money, commission or the ride lifecycle.

-- ---------------------------------------------------------------------------------------------------------------------
-- A. Safety incidents. SOS alerts are the incidents; the six states the Safety Center needs are added to the same table.
--    Stored value 'open' is shown as "New" so existing rows, the app and old clients keep working.
-- ---------------------------------------------------------------------------------------------------------------------
alter table app.sos_alerts drop constraint sos_alerts_status_check;
alter table app.sos_alerts add constraint sos_alerts_status_check
  check (status in ('open', 'acknowledged', 'investigating', 'escalated', 'resolved', 'closed'));

alter table app.sos_alerts
  add column category    text        not null default 'sos'
    check (category in ('sos', 'accident', 'harassment', 'unsafe_driving', 'route_deviation', 'vehicle_issue', 'theft', 'medical', 'other')),
  add column severity    text        not null default 'high'      -- the SOS button is high by definition; admins can change it
    check (severity in ('low', 'medium', 'high', 'critical')),
  add column assigned_to bigint      references app.users (id) on delete set null,
  add column source      text        not null default 'app' check (source in ('app', 'admin')),
  add column updated_at  timestamptz not null default now(),
  add column closed_at   timestamptz;
create index sos_alerts_assigned_idx on app.sos_alerts (assigned_to, status) where assigned_to is not null;
create index sos_alerts_ride_idx     on app.sos_alerts (ride_request_id) where ride_request_id is not null;

-- Every action on an incident. Append-only (see the trigger below). Phone numbers and exact locations are never copied in here.
create table app.safety_incident_events (
  id          bigint generated by default as identity primary key,
  incident_id bigint      not null references app.sos_alerts (id) on delete cascade,
  action      text        not null check (action in ('created', 'status', 'assigned', 'note', 'severity', 'category', 'escalated', 'reveal')),
  admin_id    bigint      references app.users (id) on delete set null,
  from_value  text,
  to_value    text,
  note        text,
  detail      jsonb       not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);
create index safety_incident_events_idx on app.safety_incident_events (incident_id, id);
alter table app.safety_incident_events enable row level security;

-- History for incidents that already exist: only what was actually recorded (when raised; who handled it, when, and the note).
insert into app.safety_incident_events (incident_id, action, to_value, created_at)
  select id, 'created', status, created_at from app.sos_alerts;
insert into app.safety_incident_events (incident_id, action, admin_id, to_value, note, created_at)
  select a.id, 'status', u.id, a.status, a.admin_note, a.handled_at
    from app.sos_alerts a left join app.users u on u.id = a.handled_by
   where a.handled_at is not null;

-- ---------------------------------------------------------------------------------------------------------------------
-- B. The audit log and the incident history cannot be edited or deleted through the database connection the app uses.
--    Cascades from a parent row (a deleted ride or user) and "set null" on a deleted admin run one trigger level deeper and are allowed.
-- ---------------------------------------------------------------------------------------------------------------------
create function app.block_log_changes() returns trigger language plpgsql as $$
begin
  if pg_trigger_depth() > 1 then
    return coalesce(new, old);
  end if;
  raise exception '% is append-only: rows cannot be changed or deleted', tg_table_name using errcode = '42501';
end $$;
create trigger admin_audit_append_only before update or delete on app.admin_audit
  for each row execute function app.block_log_changes();
create trigger safety_incident_events_append_only before update or delete on app.safety_incident_events
  for each row execute function app.block_log_changes();
create function app.block_log_truncate() returns trigger language plpgsql as $$
begin
  raise exception '% is append-only: it cannot be truncated', tg_table_name using errcode = '42501';
end $$;
create trigger admin_audit_no_truncate before truncate on app.admin_audit
  for each statement execute function app.block_log_truncate();
create trigger safety_incident_events_no_truncate before truncate on app.safety_incident_events
  for each statement execute function app.block_log_truncate();

create index admin_audit_created_idx on app.admin_audit (created_at desc, id desc);
create index admin_audit_action_idx  on app.admin_audit (action, id desc);
create index admin_audit_admin_idx   on app.admin_audit (admin_id, id desc);
create index admin_audit_target_idx  on app.admin_audit (target) where target is not null;

-- ---------------------------------------------------------------------------------------------------------------------
-- C. Instrumentation that did not exist. Driver accept, release and cancel history was overwritten on the ride row, and online
--    time was only a flag. These record changes from now on, in the database, so every code path is covered. No backfill:
--    the reports say when tracking began and never invent earlier figures.
-- ---------------------------------------------------------------------------------------------------------------------
create table app.driver_ride_events (
  id              bigint generated by default as identity primary key,
  ride_request_id bigint      not null references app.ride_requests (id) on delete cascade,
  driver_id       bigint      not null references app.users (id) on delete cascade,
  event           text        not null check (event in ('assigned', 'released', 'reassigned_away', 'cancelled_with_driver')),
  cancelled_by    text,
  created_at      timestamptz not null default now()
);
create index driver_ride_events_driver_idx on app.driver_ride_events (driver_id, created_at);
create index driver_ride_events_ride_idx   on app.driver_ride_events (ride_request_id, id);
alter table app.driver_ride_events enable row level security;

create function app.track_driver_ride() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.driver_id is not null then
      insert into app.driver_ride_events (ride_request_id, driver_id, event) values (new.id, new.driver_id, 'assigned');
    end if;
    return new;
  end if;
  if old.driver_id is null and new.driver_id is not null then
    insert into app.driver_ride_events (ride_request_id, driver_id, event) values (new.id, new.driver_id, 'assigned');
  elsif old.driver_id is not null and new.driver_id is null then
    insert into app.driver_ride_events (ride_request_id, driver_id, event) values (new.id, old.driver_id, 'released');
  elsif old.driver_id is not null and new.driver_id is distinct from old.driver_id then
    insert into app.driver_ride_events (ride_request_id, driver_id, event) values (new.id, old.driver_id, 'reassigned_away');
    insert into app.driver_ride_events (ride_request_id, driver_id, event) values (new.id, new.driver_id, 'assigned');
  end if;
  if new.status = 'cancelled' and old.status is distinct from 'cancelled' and new.driver_id is not null then
    insert into app.driver_ride_events (ride_request_id, driver_id, event, cancelled_by) values (new.id, new.driver_id, 'cancelled_with_driver', new.cancelled_by);
  end if;
  return new;
end $$;
create trigger ride_requests_track_driver_ins after insert on app.ride_requests
  for each row when (new.driver_id is not null) execute function app.track_driver_ride();
create trigger ride_requests_track_driver_upd after update of driver_id, status on app.ride_requests
  for each row when (old.driver_id is distinct from new.driver_id or old.status is distinct from new.status)
  execute function app.track_driver_ride();

create table app.driver_online_sessions (
  id         bigint generated by default as identity primary key,
  driver_id  bigint      not null references app.users (id) on delete cascade,
  started_at timestamptz not null default now(),
  ended_at   timestamptz,
  check (ended_at is null or ended_at >= started_at)
);
create unique index driver_online_one_open_uq on app.driver_online_sessions (driver_id) where ended_at is null;
create index driver_online_sessions_idx on app.driver_online_sessions (driver_id, started_at);
alter table app.driver_online_sessions enable row level security;

create function app.track_driver_online() returns trigger language plpgsql as $$
begin
  if new.is_online and not old.is_online then
    insert into app.driver_online_sessions (driver_id) values (new.id) on conflict do nothing;
  elsif old.is_online and not new.is_online then
    update app.driver_online_sessions set ended_at = now() where driver_id = new.id and ended_at is null;
  end if;
  return new;
end $$;
create trigger users_track_online after update of is_online on app.users
  for each row when (old.is_online is distinct from new.is_online) execute function app.track_driver_online();

-- Drivers online right now: their real start time was never recorded, so their session starts at the moment tracking begins.
insert into app.driver_online_sessions (driver_id) select id from app.users where is_online on conflict do nothing;
insert into app.settings (key, value) values ('analytics_tracking', jsonb_build_object('driver_events_since', now(), 'online_sessions_since', now()))
  on conflict (key) do nothing;

