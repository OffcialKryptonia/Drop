-- Driver applications: uploaded files (kept in R2), per-ride-type document requirements, review settings.

-- One row per driver and document (the old table allowed duplicates).
delete from app.driver_documents a using app.driver_documents b
 where a.driver_id = b.driver_id and a.document_id = b.document_id and a.id < b.id;
alter table app.driver_documents
  add constraint driver_documents_driver_doc_key unique (driver_id, document_id),
  add column content_type text,
  add column size_bytes   integer,
  add column uploaded_at  timestamptz;

-- A required document applies to every ride type, unless it has rows here: then only to those ride types.
create table app.document_requirements (
  id          bigint generated by default as identity primary key,
  document_id bigint not null references app.documents (id) on delete cascade,
  service_id  bigint not null references app.services (id) on delete cascade,
  unique (document_id, service_id)
);
alter table app.document_requirements enable row level security;

-- The applicant's profile photo (file in R2).
alter table app.users add column profile_image_key text;

insert into app.settings (key, value) values ('driver_min_age', '19'::jsonb), ('driver_min_licence_years', '1'::jsonb)
  on conflict (key) do nothing;
