-- Emergency contacts a rider can alert from the app.
create table if not exists app.sos_contacts (
  id             bigint generated by default as identity primary key,
  user_id        bigint      not null references app.users (id) on delete cascade,
  title          text        not null,
  contact_number text        not null,
  created_at     timestamptz not null default now()
);
create index if not exists sos_contacts_user_idx on app.sos_contacts (user_id, id);
alter table app.sos_contacts enable row level security;
