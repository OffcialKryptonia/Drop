-- PayMyRide: a passenger shares a link so someone else can pay for the trip.
alter table app.wallet_ledger drop constraint if exists wallet_ledger_kind_check;
alter table app.wallet_ledger add constraint wallet_ledger_kind_check
  check (kind in ('topup', 'ride_payment', 'ride_earning', 'commission', 'withdrawal', 'refund', 'adjustment',
                  'legacy_import', 'transfer_out', 'transfer_in', 'paymyride'));

create table app.ride_pay_links (
  id               bigint generated by default as identity primary key,
  token            text          not null unique,
  ride_request_id  bigint        not null references app.ride_requests (id) on delete cascade,
  user_id          bigint        not null references app.users (id) on delete cascade,   -- the passenger
  amount           numeric(14,2) not null check (amount > 0),
  status           text          not null default 'pending' check (status in ('pending', 'paid', 'cancelled')),
  gateway          text,                         -- korapay or pocketfi, set when paid
  reference        text unique,                  -- the gateway reference of the attempt that is being paid
  payer_name       text,
  payer_email      text,
  paid_at          timestamptz,
  created_at       timestamptz   not null default now(),
  expires_at       timestamptz   not null default now() + interval '6 hours'
);
create index ride_pay_links_ride_idx on app.ride_pay_links (ride_request_id);
create index ride_pay_links_user_idx on app.ride_pay_links (user_id, status);
alter table app.ride_pay_links enable row level security;
