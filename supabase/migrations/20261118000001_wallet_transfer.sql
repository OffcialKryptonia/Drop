-- Passenger to passenger wallet transfers, confirmed with a 4-digit transaction PIN.
alter table app.wallet_ledger drop constraint if exists wallet_ledger_kind_check;
alter table app.wallet_ledger add constraint wallet_ledger_kind_check
  check (kind in ('topup', 'ride_payment', 'ride_earning', 'commission', 'withdrawal', 'refund', 'adjustment',
                  'legacy_import', 'transfer_out', 'transfer_in'));

alter table app.users
  add column if not exists transaction_pin_hash text,
  add column if not exists pin_failed_attempts integer not null default 0,
  add column if not exists pin_locked_until timestamptz;

create table app.wallet_transfers (
  id           bigint generated by default as identity primary key,
  sender_id    bigint        not null references app.users (id) on delete restrict,
  recipient_id bigint        not null references app.users (id) on delete restrict,
  amount       numeric(14,2) not null check (amount > 0),
  note         text,
  created_at   timestamptz   not null default now(),
  check (sender_id <> recipient_id)
);
create index wallet_transfers_sender_idx on app.wallet_transfers (sender_id, created_at desc);
create index wallet_transfers_recipient_idx on app.wallet_transfers (recipient_id, created_at desc);
alter table app.wallet_transfers enable row level security;
