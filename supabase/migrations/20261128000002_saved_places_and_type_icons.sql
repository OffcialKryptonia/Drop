-- Saved places (Home, Work, other) for the "Enter your route" screen, and an uploaded ride-type picture.
create table if not exists app.saved_places (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references app.users (id) on delete cascade,
  kind       text not null check (kind in ('home', 'work', 'other')),
  label      text not null,
  address    text not null,
  lat        double precision not null check (lat between -90 and 90),
  lng        double precision not null check (lng between -180 and 180),
  created_at timestamptz not null default now()
);
create unique index if not exists saved_places_home_work_uq on app.saved_places (user_id, kind) where kind in ('home', 'work');
create index if not exists saved_places_user_idx on app.saved_places (user_id, id);
alter table app.saved_places enable row level security;
alter table app.services add column if not exists icon_file_key text;
