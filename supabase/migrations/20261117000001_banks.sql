-- Nigerian banks, microfinance banks and mobile money operators, managed from the admin panel.
create table app.banks (
  id         bigint generated by default as identity primary key,
  code       text        not null unique,
  name       text        not null,
  kind       text        not null default 'bank' check (kind in ('bank', 'mfb', 'mmo')),
  country    text        not null default 'NG',
  logo_url   text,
  active     boolean     not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index banks_active_name_idx on app.banks (active, name);
alter table app.banks enable row level security;

