-- Pickup verification: a 4-digit code the passenger shows and the driver types before the trip can start.
-- The code is stored encrypted (so the passenger's app can show it) and as a salted hash (so it is checked
-- without decrypting). Both are made by the Worker; the app never decides anything.
create table app.ride_pickup_codes (
  ride_request_id bigint primary key references app.ride_requests (id) on delete cascade,
  code_enc        text        not null,
  code_hash       text        not null,
  salt            text        not null,
  expires_at      timestamptz not null,
  failed_attempts integer     not null default 0,
  total_failed    integer     not null default 0,
  locked_until    timestamptz,
  verified_at     timestamptz,
  verified_by     bigint      references app.users (id),
  overridden_at   timestamptz,
  overridden_by   bigint      references app.users (id),
  created_at      timestamptz not null default now()
);
alter table app.ride_pickup_codes enable row level security;

create table app.ride_pickup_events (
  id              bigint generated by default as identity primary key,
  ride_request_id bigint      not null references app.ride_requests (id) on delete cascade,
  actor_id        bigint      references app.users (id),
  event           text        not null check (event in ('issued', 'verified', 'wrong_code', 'locked', 'expired', 'override')),
  created_at      timestamptz not null default now()
);
create index ride_pickup_events_ride_idx on app.ride_pickup_events (ride_request_id, id);
alter table app.ride_pickup_events enable row level security;
