-- Optional fare bidding. A bid is NOT a ride: the passenger proposes a fare, eligible drivers accept / counter / decline,
-- the passenger picks one driver, and only then (one transaction) a normal accepted ride is created at the agreed fare.
-- Everything downstream (commission, wallet, receipts, history) keeps reading app.ride_requests.fare, so nothing is duplicated.
-- Additive and idempotent: standard booking is untouched. Calling is off by default (setting "bidding".enabled = false).

-- Driver preferences, independent of each other. Standard requests stay ON for everyone; bids are opt-in.
alter table app.driver_profiles
  add column if not exists accepts_standard boolean not null default true,
  add column if not exists accepts_bids     boolean not null default false;

create table if not exists app.ride_bids (
  id               bigint generated by default as identity primary key,
  rider_id         bigint not null references app.users (id),
  service_id       bigint not null references app.services (id),
  region_id        bigint references app.regions (id),
  status           text not null default 'open' check (status in ('open', 'confirmed', 'expired', 'cancelled')),
  pickup_lat       double precision not null check (pickup_lat between -90 and 90),
  pickup_lng       double precision not null check (pickup_lng between -180 and 180),
  pickup_address   text,
  dropoff_lat      double precision not null check (dropoff_lat between -90 and 90),
  dropoff_lng      double precision not null check (dropoff_lng between -180 and 180),
  dropoff_address  text,
  stops            jsonb not null default '[]'::jsonb,       -- the full route the fare covers: [{lat,lng,address}]
  distance         numeric(12, 3) not null,
  distance_unit    text not null check (distance_unit in ('km', 'mile')),
  duration_minutes numeric(10, 2) not null,
  route_source     text not null check (route_source in ('google', 'osrm', 'estimate')),
  currency         char(3) not null default 'NGN',
  payment_method   text not null check (payment_method in ('cash', 'wallet', 'card', 'virtual_account')),
  options          jsonb not null default '[]'::jsonb,
  estimate_fare    numeric(14, 4) not null check (estimate_fare >= 0),   -- DROP's own price, computed on the server
  offer_fare       numeric(14, 4) not null check (offer_fare > 0),       -- the passenger's current offer
  rounds_used      int not null default 0,                                -- passenger revisions of the whole bid
  client_key       text,                                                  -- stops a double tap creating two bids
  expires_at       timestamptz not null,
  ride_request_id  bigint references app.ride_requests (id),
  selected_driver_id bigint references app.users (id),
  agreed_fare      numeric(14, 4),
  close_reason     text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  closed_at        timestamptz
);
create index if not exists ride_bids_rider_idx on app.ride_bids (rider_id, created_at desc);
create index if not exists ride_bids_open_idx on app.ride_bids (expires_at) where status = 'open';
create index if not exists ride_bids_service_open_idx on app.ride_bids (service_id) where status = 'open';
-- A passenger can have only as many live bids as the admin allows; the hard floor is one (a unique index) unless raised in code.
create unique index if not exists ride_bids_client_key_uniq on app.ride_bids (rider_id, client_key) where client_key is not null;
drop trigger if exists ride_bids_touch on app.ride_bids;
create trigger ride_bids_touch before update on app.ride_bids for each row execute function app.touch_updated_at();
alter table app.ride_bids enable row level security;

-- One negotiation thread per driver per bid.
create table if not exists app.ride_bid_responses (
  id          bigint generated by default as identity primary key,
  bid_id      bigint not null references app.ride_bids (id) on delete cascade,
  driver_id   bigint not null references app.users (id),
  status      text not null check (status in (
                'driver_accepted_offer',            -- the driver took the passenger's fare as it stands
                'counteroffered',                   -- driver proposed a different fare; waiting for the passenger
                'rider_revised',                    -- passenger proposed a different fare to this driver; waiting for the driver
                'passenger_accepted_counteroffer',  -- both sides now agree on amount
                'selected',                         -- the passenger picked this driver: the ride exists
                'declined',                         -- driver said no (or withdrew)
                'rejected',                         -- passenger turned the counteroffer down
                'expired',
                'lost')),                           -- another driver was selected, or the bid closed
  amount      numeric(14, 4) not null check (amount > 0),   -- the fare currently on the table in this thread
  rounds      int not null default 0,                         -- counteroffers/revisions used in this thread
  expires_at  timestamptz not null,
  pickup_m    double precision,                               -- driver's distance to the pickup when they first answered
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (bid_id, driver_id)
);
create index if not exists ride_bid_responses_driver_idx on app.ride_bid_responses (driver_id, updated_at desc);
create index if not exists ride_bid_responses_live_idx on app.ride_bid_responses (bid_id)
  where status in ('driver_accepted_offer', 'counteroffered', 'rider_revised', 'passenger_accepted_counteroffer');
drop trigger if exists ride_bid_responses_touch on app.ride_bid_responses;
create trigger ride_bid_responses_touch before update on app.ride_bid_responses for each row execute function app.touch_updated_at();
alter table app.ride_bid_responses enable row level security;

-- Negotiation history, append only.
create table if not exists app.ride_bid_events (
  id          bigint generated by default as identity primary key,
  bid_id      bigint not null references app.ride_bids (id) on delete cascade,
  response_id bigint references app.ride_bid_responses (id) on delete cascade,
  actor_role  text not null check (actor_role in ('rider', 'driver', 'system')),
  actor_id    bigint references app.users (id),
  action      text not null,
  amount      numeric(14, 4),
  note        text,
  created_at  timestamptz not null default now()
);
create index if not exists ride_bid_events_bid_idx on app.ride_bid_events (bid_id, id);
alter table app.ride_bid_events enable row level security;

-- The ride that came out of a bid. Null for every standard ride.
alter table app.ride_requests add column if not exists bid_id bigint references app.ride_bids (id);
create unique index if not exists ride_requests_bid_uniq on app.ride_requests (bid_id) where bid_id is not null;

-- Defaults. Bidding is OFF until an admin switches it on. Policy lives here, never in the apps.
insert into app.settings (key, value) values ('bidding', jsonb_build_object(
  'enabled', false,
  'min_percent', 70,            -- lowest offer, as a % of DROP's estimate
  'max_percent', 150,           -- highest offer, as a % of DROP's estimate
  'absolute_min', 0,            -- never below this amount (0 = no floor)
  'absolute_max', 0,            -- never above this amount (0 = no ceiling)
  'max_rounds', 3,              -- counteroffers / revisions per driver thread (and passenger revisions per bid)
  'bid_expiry_seconds', 180,    -- how long a bid stays open
  'offer_expiry_seconds', 90,   -- how long a driver response or counteroffer stays valid
  'max_active_bids', 1,         -- live bids per passenger
  'max_bids_per_hour', 10,      -- anti-spam
  'max_cancelled_per_day', 6,   -- repeated cancelled bids are blocked
  'overrides', '[]'::jsonb      -- [{region_id?, service_id?, enabled?, min_percent?, max_percent?, absolute_min?, absolute_max?}]
)) on conflict (key) do nothing;
