-- Admin roles and permissions, and fully admin-managed ride types (app.services).
-- Permission names follow the legacy pattern "<module> list|add|edit|delete".

-- ---------------------------------------------------------------------------
-- Roles and permissions
-- ---------------------------------------------------------------------------
create table app.admin_roles (
  id         bigint generated by default as identity primary key,
  name       text    not null unique check (name ~ '^[a-z0-9_-]{2,40}$'),
  label      text    not null,
  is_super   boolean not null default false,   -- full access, cannot be edited or deleted
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table app.admin_role_permissions (
  role_id    bigint not null references app.admin_roles (id) on delete cascade,
  permission text   not null,
  primary key (role_id, permission)
);

alter table app.users add column admin_role_id bigint references app.admin_roles (id) on delete set null;

create trigger admin_roles_touch before update on app.admin_roles
  for each row execute function app.touch_updated_at();

alter table app.admin_roles            enable row level security;
alter table app.admin_role_permissions enable row level security;

-- The built-in super admin role. Every existing admin keeps full access.
insert into app.admin_roles (name, label, is_super) values ('admin', 'Super admin', true);
update app.users set admin_role_id = (select id from app.admin_roles where name = 'admin')
 where user_type = 'admin';

-- ---------------------------------------------------------------------------
-- Ride types: extra fields on app.services
-- ---------------------------------------------------------------------------
alter table app.services
  add column category           text    not null default 'car',
  add column icon_url           text,
  add column photo_url          text,
  add column name_i18n          jsonb   not null default '{}'::jsonb,   -- { "ha": "...", "yo": "..." }
  add column description_i18n   jsonb   not null default '{}'::jsonb,
  add column booking_modes      text[]  not null default array['now'],  -- now, scheduled, multi_drop, bidding, for_other
  add column payment_methods    text[]  not null default array['cash','wallet'],
  add column sort_order         integer not null default 0,
  add column badge              text,                                   -- e.g. New, Popular
  add column min_driver_rating  numeric(3, 2),
  add column min_wallet_balance numeric(14, 4),
  add column working_hours      jsonb,                                  -- null = always available
  add column deleted_at         timestamptz;

alter table app.services
  add constraint services_booking_modes_valid
    check (booking_modes <@ array['now','scheduled','multi_drop','bidding','for_other']),
  add constraint services_payment_methods_valid
    check (payment_methods <@ array['cash','wallet','card','virtual_account']);

create index services_sort_idx on app.services (sort_order, id) where deleted_at is null;

-- Extra options riders can tick (child seat, luggage, pet friendly...), priced by the admin.
create table app.service_options (
  id         bigint generated by default as identity primary key,
  name       text    not null,
  name_i18n  jsonb   not null default '{}'::jsonb,
  price      numeric(14, 4) not null default 0 check (price >= 0),
  status     boolean not null default true,
  sort_order integer not null default 0,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger service_options_touch before update on app.service_options
  for each row execute function app.touch_updated_at();
alter table app.service_options enable row level security;

insert into app.service_options (name, price, sort_order) values
  ('Child seat', 500, 1), ('Extra luggage', 500, 2), ('Pet friendly', 1000, 3),
  ('Wheelchair access', 0, 4), ('Quiet ride', 0, 5);
